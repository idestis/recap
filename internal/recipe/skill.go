package recipe

import (
	"fmt"
	"strings"
)

// Skill renders a recipe as a Claude Code skill (SKILL.md). The skill tells the
// agent to execute through `recap run`, so preflight, risk prompts and trust
// tracking apply to agents exactly as to people (SPEC D-17, D-26).
func Skill(doc string) (string, error) {
	fm := frontMatter(doc)
	id, title := fm["id"], fm["title"]
	if id == "" || title == "" {
		return "", fmt.Errorf("recipe has no id or title in its front matter")
	}
	body := doc
	if strings.HasPrefix(doc, "---\n") {
		if _, rest, ok := strings.Cut(doc[4:], "\n---\n"); ok {
			body = rest
		}
	}
	body = strings.TrimSpace(body)
	// The recipe's own "# Title" would duplicate the skill heading.
	if strings.HasPrefix(body, "# ") {
		_, body, _ = strings.Cut(body, "\n")
		body = strings.TrimSpace(body)
	}
	vars := strings.Fields(strings.NewReplacer("[", " ", "]", " ", ",", " ").Replace(fm["vars"]))
	risk := fm["risk"]

	var varFlags []string
	for _, v := range vars {
		varFlags = append(varFlags, "--var "+v+"=…")
	}
	run := strings.TrimSpace("recap run " + id + " " + strings.Join(varFlags, " "))

	desc := title + "."
	if s := firstSentence(section(body, "Situation")); s != "" {
		desc += " " + s
	}
	desc += " Use when the user hits this situation or asks to " + strings.ToLower(title) + ". Risk: " + risk + "."
	if len(desc) > 1000 {
		desc = desc[:997] + "..."
	}

	var b strings.Builder
	fmt.Fprintf(&b, "---\nname: %s\ndescription: %s\n---\n\n# %s\n\n", id, oneLine(desc), title)
	b.WriteString("Generated by recap from a reviewed recipe (`recipes/" + id + ".md`). Run it through recap so risk gates and trust tracking apply.\n\n")
	b.WriteString("## How to run\n\n")
	fmt.Fprintf(&b, "1. Preview, which changes nothing: `%s`\n", run)
	if len(vars) > 0 {
		fmt.Fprintf(&b, "2. Ask the user for any value you don't know: %s.\n", "`"+strings.Join(vars, "`, `")+"`")
	} else {
		b.WriteString("2. Check the preconditions below with the user.\n")
	}
	fmt.Fprintf(&b, "3. Execute: `%s --execute`. Without a terminal recap stops before the first risky step: show the user that step, and only after they confirm, run again with `--yes`.\n\n", run)
	b.WriteString("Do not run the commands below directly and do not change them; if the situation differs, tell the user instead.\n\n")
	b.WriteString("## Recipe\n\n")
	b.WriteString(demote(body))
	b.WriteString("\n")
	return b.String(), nil
}

// section returns the text under "## name" up to the next heading.
func section(body, name string) string {
	_, rest, ok := strings.Cut(body, "## "+name+"\n")
	if !ok {
		return ""
	}
	rest, _, _ = strings.Cut(rest, "\n## ")
	return strings.TrimSpace(rest)
}

func firstSentence(s string) string {
	s = oneLine(s)
	if i := strings.Index(s, ". "); i > 0 {
		return s[:i+1]
	}
	return s
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// demote turns "## X" into "### X" so the recipe nests under "## Recipe".
func demote(md string) string {
	lines := strings.Split(md, "\n")
	inFence := false
	for i, l := range lines {
		if strings.HasPrefix(strings.TrimSpace(l), "```") {
			inFence = !inFence
		}
		if !inFence && strings.HasPrefix(l, "#") {
			lines[i] = "#" + l
		}
	}
	return strings.Join(lines, "\n")
}
